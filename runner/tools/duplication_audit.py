#!/usr/bin/env python3
"""Measure the tree's dormant code: the duplication audit's tool.

# Agent-Stamp: 00000000-muse-7e57-d0c5-58316a922026

The standing audit (docs/infrastructure-documents/project/
duplication-audit.md, 2026-11-03) states the method; this tool
operationalizes it so a fresh audit is a run, not a
reconstruction. The fresh audit that first carries it stands
in docs/infrastructure-documents/project/dormant-code-audit.md.

The method, as the standing audit states it:

- Near-duplicate code: a sliding window of 8 normalized
  non-blank, non-comment lines over the Python files. A line
  counts when it sits in a window that also occurs at another
  position (another file, or another place in the same file).
  The figure is an upper bound: it counts both sides of every
  repetition and misses clones shorter than the window or
  heavily renamed.
- Exact copies: tracked files grouped by content hash; the
  lines of every copy past the first count.
- Unreferenced Python files: a file counts as referenced when
  another tracked file names its module or its path, or when
  it stands where the suite's discovery reaches it
  (runner/tests/). Package __init__ files are referenced by
  their package's path.
- Generated files: a text file whose opening lines carry a
  generated marker.

    python3 runner/tools/duplication_audit.py [--root PATH]
        Print the human summary for the tree at PATH (default:
        this checkout).
    python3 runner/tools/duplication_audit.py --json
        Print the measure as JSON: the shape the audit record
        and the statistics facts are written from.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys

WINDOW = 8
GENERATED_MARKERS = ("generated by", "automatically generated",
                     "do not edit")
DISCOVERY_PREFIX = os.path.join("runner", "tests") + os.sep


def repo_root():
    return os.path.dirname(os.path.dirname(os.path.dirname(
        os.path.abspath(__file__))))


def tracked_files(root):
    """Every file the audit reads, as sorted relative paths.

    A git checkout answers from its index of tracked files; a
    plain directory is walked. .git itself is never read.
    """
    if os.path.isdir(os.path.join(root, ".git")):
        out = subprocess.run(
            ["git", "-C", root, "ls-files"],
            capture_output=True, text=True, check=True).stdout
        return sorted(p for p in out.splitlines() if p)
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d != ".git"]
        for name in filenames:
            found.append(os.path.relpath(
                os.path.join(dirpath, name), root))
    return sorted(found)


def _read_bytes(root, rel):
    with open(os.path.join(root, rel), "rb") as fh:
        return fh.read()


def _read_text(root, rel):
    return _read_bytes(root, rel).decode("utf-8", errors="replace")


def count_lines(text):
    if not text:
        return 0
    return len(text.splitlines())


def normalized_lines(text):
    """The audit's line shape: stripped, non-blank, non-comment."""
    out = []
    for raw in text.splitlines():
        line = raw.strip()
        if line and not line.startswith("#"):
            out.append(line)
    return out


def near_duplicate_lines(root, python_files):
    """Per-file near-duplicate line counts, by the window method.

    Returns {relpath: (raw_lines, normalized_count, dup_count)}.
    """
    per_file = {}
    window_positions = {}
    sequences = {}
    for rel in python_files:
        text = _read_text(root, rel)
        seq = normalized_lines(text)
        sequences[rel] = seq
        per_file[rel] = [count_lines(text), len(seq), 0]
        for start in range(len(seq) - WINDOW + 1):
            window = tuple(seq[start:start + WINDOW])
            window_positions[window] = \
                window_positions.get(window, 0) + 1
    repeated = {w for w, n in window_positions.items() if n >= 2}
    for rel, seq in sequences.items():
        marked = bytearray(len(seq))
        for start in range(len(seq) - WINDOW + 1):
            if tuple(seq[start:start + WINDOW]) in repeated:
                for pos in range(start, start + WINDOW):
                    marked[pos] = 1
        per_file[rel][2] = sum(marked)
    return {rel: tuple(vals) for rel, vals in per_file.items()}


def exact_copies(root, files):
    """Exact-copy lines beyond the first copy, by content hash.

    Returns (total_lines, [(kept_path, [copy_paths], lines_each)]).
    """
    by_hash = {}
    for rel in files:
        digest = hashlib.sha256(_read_bytes(root, rel)).hexdigest()
        by_hash.setdefault(digest, []).append(rel)
    total = 0
    groups = []
    for digest in sorted(by_hash):
        paths = sorted(by_hash[digest])
        if len(paths) < 2:
            continue
        lines_each = count_lines(_read_text(root, paths[0]))
        total += lines_each * (len(paths) - 1)
        groups.append((paths[0], paths[1:], lines_each))
    return total, groups


def unreferenced_python(root, files, python_files):
    """Python files nothing else names and discovery cannot reach.

    The reference corpus is the tree's own text: every tracked
    file that decodes as UTF-8, read once. A candidate is
    referenced when its dotted module path or its bare module
    name appears in the corpus outside the candidate's own
    text. Tests are reached by discovery and package __init__
    files by their package; neither is a candidate.
    """
    corpus_parts = []
    own_text = {}
    for rel in files:
        try:
            text = _read_bytes(root, rel).decode("utf-8")
        except (UnicodeDecodeError, ValueError):
            continue
        corpus_parts.append(text)
        if rel in python_files:
            own_text[rel] = text
    corpus = "\n".join(corpus_parts)
    unreferenced = []
    for rel in python_files:
        if rel.replace(os.sep, "/").startswith("runner/tests/"):
            continue
        if os.path.basename(rel) == "__init__.py":
            continue
        dotted = rel[:-3].replace(os.sep, ".")
        stem = os.path.basename(rel)[:-3]
        own = own_text.get(rel, "")
        named_elsewhere = (
            corpus.count(dotted) > own.count(dotted)
            or corpus.count(stem) > own.count(stem))
        if not named_elsewhere:
            unreferenced.append(rel)
    return sorted(unreferenced)


def generated_marked(root, files):
    """Text files whose opening lines carry a generated marker."""
    marked = []
    for rel in files:
        try:
            text = _read_bytes(root, rel).decode("utf-8")
        except (UnicodeDecodeError, ValueError):
            continue
        head = "\n".join(text.splitlines()[:5]).lower()
        if any(marker in head for marker in GENERATED_MARKERS):
            marked.append(rel)
    return sorted(marked)


def _percent(part, whole):
    if not whole:
        return 0.0
    return round(100.0 * part / whole, 2)


def audit(root):
    """The whole measure of the tree at root, as a dict."""
    files = tracked_files(root)
    python_files = [f for f in files if f.endswith(".py")]
    tree_lines = 0
    for rel in files:
        tree_lines += count_lines(_read_text(root, rel))
    per_file = near_duplicate_lines(root, python_files)
    python_lines = sum(v[0] for v in per_file.values())
    near_lines = sum(v[2] for v in per_file.values())
    test_lines = sum(v[2] for rel, v in per_file.items()
                     if rel.replace(os.sep, "/").startswith(
                         "runner/tests/"))
    prod_lines = near_lines - test_lines
    exact_lines, exact_groups = exact_copies(root, files)
    near_percent = _percent(near_lines, tree_lines)
    top = sorted(per_file.items(), key=lambda kv: -kv[1][2])[:20]
    commit = None
    if os.path.isdir(os.path.join(root, ".git")):
        commit = subprocess.run(
            ["git", "-C", root, "rev-parse", "HEAD"],
            capture_output=True, text=True).stdout.strip() or None
    return {
        "commit": commit,
        "files_tracked": len(files),
        "tree_lines": tree_lines,
        "python_files": len(python_files),
        "python_lines": python_lines,
        "near_duplicate_lines": near_lines,
        "near_duplicate_percent_tree": near_percent,
        "near_duplicate_percent_python": _percent(
            near_lines, python_lines),
        "near_duplicate_test_lines": test_lines,
        "near_duplicate_production_lines": prod_lines,
        "non_latent_percent": round(100.0 - near_percent, 2),
        "exact_copy_lines": exact_lines,
        "exact_copy_percent_tree": _percent(exact_lines, tree_lines),
        "exact_copy_groups": [
            {"kept": kept, "copies": copies, "lines_each": lines}
            for kept, copies, lines in exact_groups],
        "unreferenced_python": unreferenced_python(
            root, files, set(python_files)),
        "generated_marked": generated_marked(root, files),
        "top_files": [
            {"path": rel, "lines": vals[0],
             "normalized_lines": vals[1],
             "near_duplicate_lines": vals[2]}
            for rel, vals in top if vals[2] > 0],
    }


def _summary(result):
    lines = [
        "tree: %d tracked files, %d lines" % (
            result["files_tracked"], result["tree_lines"]),
        "python: %d files, %d lines" % (
            result["python_files"], result["python_lines"]),
        "near-duplicate: %d lines — %s%% of the tree, %s%% of "
        "the Python" % (
            result["near_duplicate_lines"],
            result["near_duplicate_percent_tree"],
            result["near_duplicate_percent_python"]),
        "  in tests: %d — in production: %d" % (
            result["near_duplicate_test_lines"],
            result["near_duplicate_production_lines"]),
        "non-latent: %s%%" % result["non_latent_percent"],
        "exact copies: %d lines beyond the first copy — %s%% "
        "of the tree" % (
            result["exact_copy_lines"],
            result["exact_copy_percent_tree"]),
        "unreferenced python files: %d" % len(
            result["unreferenced_python"]),
        "generated files checked in: %d" % len(
            result["generated_marked"]),
    ]
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Measure the tree's dormant code.")
    parser.add_argument("--root", default=repo_root(),
                        help="the tree to measure (default: this "
                             "checkout)")
    parser.add_argument("--json", action="store_true",
                        help="print the measure as JSON")
    args = parser.parse_args(argv)
    result = audit(os.path.abspath(args.root))
    if args.json:
        print(json.dumps(result, indent=2, sort_keys=True))
    else:
        print(_summary(result))
    return 0


if __name__ == "__main__":
    sys.exit(main())
