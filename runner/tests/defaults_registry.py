def _root():
    import runner
    return os.path.dirname(os.path.dirname(os.path.abspath(runner.__file__)))


class RegistryShapeTests(unittest.TestCase):
    def test_rows_are_unique_and_complete(self):
        keys = [(r["scope"], r["key"]) for r in ROWS]
        self.assertEqual(len(keys), len(set(keys)), "duplicate rows")
        for r in ROWS:
            self.assertIn(r["policy"], ("default", "refuse"), r["key"])
            self.assertIn(r["probe"], ("confval", "refuse",
                                       "policy-conflict", "handwritten"),
                          r["key"])
            self.assertTrue(r["reader"], r["key"])
            if r["policy"] == "refuse":
                self.assertNotEqual(r["probe"], "confval", r["key"])

    def test_reader_sites_resolve(self):
        # Every reader site names a function that exists in
        # the named file. An extraction that moves a reader
        # (apply_result_policy to runner/ops/policy.py,
        # 2026-10-25) must move its rows in the same
        # commit; before this guard, two rows pointed at
        # a function runner.py no longer held and nothing
        # noticed.
        cache = {}

        def funcs(path):
            if path not in cache:
                with open(os.path.join(_root(), path),
                          encoding="utf-8") as fh:
                    tree = ast.parse(fh.read())
                cache[path] = {
                    n.name for n in ast.walk(tree)
                    if isinstance(n, (ast.FunctionDef,
                                      ast.AsyncFunctionDef))}
            return cache[path]

        for r in ROWS:
            sites = {r["reader"]} | set(r["reader_sites"])
            for site in sites:
                path, _, fn = site.rpartition(":")
                with self.subTest(key=r["key"], site=site):
                    self.assertIn(fn, funcs(path))

    def test_row_count_matches_the_documented_keys(self):
        # 49 core keys + 51 extension tunables, as extracted and
        # doc-verified at the commit that added this registry;
        # +4 core rows in the 2026-10-25 queue D refill
        # (oracle_mode and the oracle_opinion_* enum family),
        # then +4 more the same day (protocol_v2 and the
        # oracle_opinion_model / oracle_learning booleans),
        # then +3 more (answer_only, mail_tls_required,
        # job_encryption), then +6 more (the remediation
        # family: mode plus its five numeric settings),
        # then +5 more (the log-bounds family), then
        # extension_review (a refuse-class row), then
        # the local-signals pair, then the two M1b
        # size caps (refuse class).
        # then the two outbox stash keys (review item 1) and the
        # result body cap (review item 4).
        # then the two --once drain flags (hosting, Phase 0).
        self.assertEqual(132, len(ROWS))
        self.assertEqual(81, sum(1 for r in ROWS if r["scope"] == "core"))
        self.assertEqual(51, sum(1 for r in ROWS if r["scope"] == "extension"))


class DocDriftGuardTests(unittest.TestCase):
    def test_doc_lines_still_carry_their_default(self):
        root = _root()
        cache = {}
        offenders = []
        for r in ROWS:
            if r["doc_status"] == "unverified":
                continue
            path = os.path.join(root, r["doc_file"])
            if path not in cache:
                with open(path, encoding="utf-8") as fh:
                    cache[path] = fh.read().splitlines()
            lines = cache[path]
            if r["doc_line"] > len(lines):
                offenders.append((r["key"], "doc line past end of file"))
                continue
            if r["doc_token"] not in lines[r["doc_line"] - 1]:
                offenders.append((r["key"], r["doc_file"], r["doc_line"],
                                  r["doc_token"]))
        self.assertEqual([], offenders,
                         "doc lines moved or defaults changed; update "
                         "the registry row with the doc: %s" % (offenders,))

    def test_unverified_set_is_exactly_the_known_set(self):
        unverified = {r["key"] for r in ROWS
                      if r["doc_status"] == "unverified"}
        self.assertEqual(KNOWN_UNDOCUMENTED, unverified)


def _confval_call_sites():
    """Every confval reader call in runner/, as "path:function"."""
    root = _root()
    sites = set()
    readers = {"number", "integer", "port", "choice", "is_number"}
    for dirpath, dirnames, filenames in os.walk(os.path.join(root, "runner")):
        # runner/tests/ is the suite, not a reader.
        dirnames[:] = [d for d in dirnames if not (
            d == "tests"
            and os.path.normpath(dirpath) == os.path.normpath(
                os.path.join(root, "runner")))]
        if "__pycache__" in dirpath:
            continue
        for name in filenames:
            if not name.endswith(".py"):
                continue
            path = os.path.join(dirpath, name)
            # Rows and exemptions spell paths with "/"; Windows
            # walks with "\\", and the first Windows run of this
            # guard failed every row on the separator alone.
            rel = os.path.relpath(path, root).replace(os.sep, "/")
            with open(path, encoding="utf-8") as fh:
                tree = ast.parse(fh.read())
            stack = []

            def visit(node, stack=stack, rel=rel):
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    stack = stack + [node.name]
                if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
                    if node.func.attr in readers and isinstance(
                            node.func.value, ast.Name) and \
                            node.func.value.id in ("confval", "_confval"):
                        fn = stack[-1] if stack else "<module>"
                        sites.add("%s:%s" % (rel, fn))
                for child in ast.iter_child_nodes(node):
                    visit(child, stack, rel)

            visit(tree)
    return sites


class ConfvalCoverageGuardTests(unittest.TestCase):
    def test_every_confval_call_site_has_a_registry_row(self):
        sites = _confval_call_sites()
        self.assertGreater(len(sites), 20, "scan found too few sites")
        covered = set()
        for r in ROWS:
            covered.update(r["reader_sites"])
        missing = sites - covered - COVERAGE_EXEMPT_SITES
        self.assertEqual(set(), missing,
                         "confval call sites with no registry row: %s"
                         % (sorted(missing),))

    def test_exempt_sites_really_exist(self):
        sites = _confval_call_sites()
        for site in COVERAGE_EXEMPT_SITES:
            self.assertIn(site, sites)


