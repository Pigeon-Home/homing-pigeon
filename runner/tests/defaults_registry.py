"""The defaults registry: every documented numeric or enum key, its
documented default, its reader, and its present-but-invalid policy.

Step 4 of the campaign plan. The first campaign built this table
by hand inside the docstrings of runner/tests/test_doc_default_divergences.py
(72 classes, 226 tests). This module is that table, as data:

    key          the config key (extension tunables are scoped
                 "name (extension)")
    scope        "core" (runner config, job fields, query
                 parameters, transport blocks) or "extension"
                 (an runner/extensions/* tunable)
    kind         integer / number / enum / boolean / string
    default      the documented default (for
                 key_policies.<key_id>.max_timeout_sec: None --
                 there is no default; absence means no cap)
    doc_file     the document that states the default
    doc_line     its line in that document, at the commit that
                 added this registry
    doc_token    the text the doc-drift guard requires on that
                 line (usually the default value itself)
    doc_status   "verified" (the line states the default),
                 "sketch" (the line is a documented example or
                 config sketch carrying the value), or
                 "unverified" (no current doc line states the
                 default; the row rests on the reader and the
                 campaign record -- see KNOWN_UNDOCUMENTED)
    reader       the read site, "path:function"
    reader_sites every read site for the key, same format
    policy       "default" or "refuse" -- Decision 1 (2026-10-23):
                 what a wrong value changes decides. `refuse`
                 (ports, bind addresses, key policies, paging
                 thresholds, security modes, secrets) means the
                 runner refuses to start and names the setting;
                 `default` means the value reads as the documented
                 default and is named in the startup warning.
    lo / hi      the reader's usable bounds, where the reader
                 states them (None = unbounded on that side)
    probe        how the table-driven hunt (step 5,
                 runner/tests/test_defaults_table_hunt.py) exercises the
                 row: "confval" (through runner/guard/confval.py, the
                 reader the code uses), "refuse" (through the
                 refusing reader itself), "policy-conflict"
                 (policy `refuse`, code still reads as default --
                 recorded as failing-by-design divergences in the
                 hunt; no row carries it since Q3, 2026-10-24,
                 moved the last three rows to "refuse" when their
                 readers moved), or "handwritten" (covered by the named
                 divergence class; the hunt asserts it exists)
    test         the hand-written divergence class that covers
                 the row, or "" -- a row with no test and no
                 table coverage is a second-run target.

Two guards live in this module and run both here
(`python -m unittest runner.tests.defaults_registry`) and, by import,
in the default discovery through runner/tests/test_defaults_table_hunt.py:

- DocDriftGuardTests: every verified/sketch row's doc line still
  carries its token; the unverified set is exactly
  KNOWN_UNDOCUMENTED, so a row cannot quietly lose its doc.
- ConfvalCoverageGuardTests: every confval call site in runner/
  belongs to some row's reader_sites. A key added through
  confval without a registry row fails this guard -- that is the
  shape of the next divergence, caught at the door.

Provenance: rows were extracted from the divergence docstrings,
runner/guard/confval.py's call sites, and the current docs, and each
doc line was re-verified against the docs at this commit.
"""

