#!/usr/bin/env python3
"""Fuzz family for the transport log relay (runner/transports.py).

test_transport_log_relay.py pins the relay's designed behaviors
with hand-picked cases. This module attacks the same code the way
the field failure actually behaved -- adversarially and at volume:

  - the level-prefix parser gets ~2,000 generated line shapes
    (level spellings, separators, unicode, embedded prefixes,
    boundary spellings like INFORMATION:/WARNINGS:) and must hold
    its invariants on every one;
  - the pump gets generated byte streams (invalid UTF-8, split
    multibyte sequences, blank floods, unterminated tails, very
    long lines) and must lose nothing, in order, in both sinks;
  - the pump's failure paths -- the ones a quiet afternoon never
    exercises -- are forced: poisoned (non-bytes) stream items, a
    stream that raises mid-iteration, a sidecar whose open fails,
    a sidecar write that fails and must reopen, a reopen that also
    fails, and a sidecar close that raises at EOF;
  - the supervisor branches the relay change touched: the Windows
    creationflags arm of _start_one, check() after stop(), and
    the 60-second settled reset of the restart counter.

Generators are seeded; every run is byte-for-byte reproducible.
"""

